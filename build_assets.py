"""Embed the PNG/JPG assets as data-URIs into src/assets-data.js so the game
also runs straight from file:// (no server needed, and recolouring works).
Run after replacing any image:  python3 tools/build_assets.py"""
import base64, os, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for folder in ('characters', 'backgrounds'):
    d = os.path.join(ROOT, 'assets', folder)
    for f in sorted(os.listdir(d)):
        name, ext = os.path.splitext(f)
        if ext.lower() not in ('.png', '.jpg', '.jpeg', '.webp'): continue
        mime = 'image/png' if ext.lower()=='.png' else ('image/webp' if ext.lower()=='.webp' else 'image/jpeg')
        out[name] = f'data:{mime};base64,' + base64.b64encode(open(os.path.join(d,f),'rb').read()).decode()
        print('embedded', folder + '/' + f)
with open(os.path.join(ROOT,'src','assets-data.js'),'w') as fh:
    fh.write('/* AUTO-GENERATED by tools/build_assets.py - do not edit by hand */\n')
    fh.write('window.ASSET_DATA = ' + json.dumps(out) + ';\n')
